static bool contains(const std::vector<std::string>& v, const std::string& s)
{
    for (std::size_t i = 0; i < v.size(); ++i)
        if (v[i] == s)
            return true;
    return false;
}

int main()
{
    {
        std::ofstream out("/embedded32.o", std::ios::binary);
        out.write(embedded_elf, sizeof(embedded_elf) - 1);
        out.close();
        CHECK(static_cast<bool>(out));   // MEMFS write succeeded
    }

    // Parse the object file: section list and symbol table.
    boost::dll::library_info li("/embedded32.o");
    std::vector<std::string> sections = li.sections();
    CHECK(contains(sections, ".text"));
    CHECK(contains(sections, ".symtab"));

    std::vector<std::string> syms = li.symbols();
    CHECK(contains(syms, "embedded_alpha"));
    CHECK(contains(syms, "embedded_beta"));
    CHECK(syms.size() >= 2);             // both exported functions parsed

    // Second parse on the same object stays consistent.
    boost::dll::library_info li2("/embedded32.o");
    CHECK(li2.symbols().size() == syms.size());

    std::cout << "boost-dll OK\n";
    return 0;
}
