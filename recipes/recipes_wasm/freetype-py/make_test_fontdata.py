"""Embed the sdist's example fonts into test_fontdata.py.

pytester only copies test_*.py files into the wasm file system, so the fonts
are shipped as base64 strings in a generated test_fontdata.py module (runs on
the host, before pytester).
"""
import base64
import os

FONTS = ["Vera.ttf", "VeraMono.ttf", "SourceSansVariable-Roman.otf"]

with open("test_fontdata.py", "w") as out:
    out.write("# generated by make_test_fontdata.py\nFONTS = {\n")
    for name in FONTS:
        with open(os.path.join("examples", name), "rb") as f:
            data = base64.b64encode(f.read()).decode("ascii")
        out.write(f"    {name!r}: {data!r},\n")
    out.write("}\n")
print("wrote test_fontdata.py with", ", ".join(FONTS))
