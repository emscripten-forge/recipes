#!/usr/bin/env python3
"""Generate the boost-cpp recipe outputs.

Two layouts are supported:

  merged (default)  two packages:
                    libboost-headers  all of include/boost + the header-only
                                      modules' CMake configs
                    libboost-static   the compiled modules' static archives
                                      + their CMake configs; depends on
                                      libboost-headers
  modules           the historical per-module layout (one package per Boost
                    module, compiled ones with a -static suffix). Kept for
                    later reuse; its output is written to out-dir/modules/.

Usage:
  gen_boost_deps.py [--layout merged|modules] [--update-recipe] <boost-root> [out-dir]
    <boost-root>  Boost git checkout with submodules: libs/<m>/include/
                  present plus the merged boost/ tree from `./b2 headers`.
                  NOT a release tarball: those ship no libs/<m>/include/, so
                  module ownership cannot be derived.
    out-dir       default: scripts/out (relative to this file)

Writes out-dir/deps.json (layout-independent module/dependency data) and
out-dir/recipe_outputs.yaml (PyYAML required). Test .cpp files are NEVER
generated: they live hand-authored, flat, in tests/test_<module>.cpp.

The generated region of recipe.yaml must stay byte-identical to
recipe_outputs.yaml. In merged mode the script asserts this and exits non-zero
on drift; pass --update-recipe to splice recipe.yaml in place instead.

Splice step (one-time after recipe.yaml structural edits):
  replace everything between the '# >>> generated' and '# <<< generated' lines
  (inclusive) with the content of out-dir/recipe_outputs.yaml.
"""

from __future__ import annotations

import argparse
import graphlib
import json
import os
import re
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator

import yaml

HERE = Path(__file__).resolve().parent
RECIPE_FILE = HERE.parent / "recipe.yaml"
OUT_DEFAULT = HERE / "out"
BOOSTDEP_FILE = HERE / "boostdep_deps.json"  # vendored by gen_boostdep_deps.py
SKIP_FILE = HERE.parent / "build.sh"  # BOOST_SKIP_MODULES="..." single source of truth

ModuleKey = str          # boostdep module name ('filesystem', 'numeric~interval', ...)
PkgName = str            # conda package name ('boost-filesystem', ...)
Claim = str              # 'include/boost/<path>[/**]' package-content entry

INC_RE = re.compile(r'#\s*include\s*[<"](boost/[A-Za-z0-9_./]+)[>"]')
HEADER_SUFFIXES = (".hpp", ".h", ".ipp")

GENERATED_HEADER = "# >>> generated by scripts/gen_boost_deps.py - do not edit by hand"
GENERATED_FOOTER = "# <<< generated"
GENERATED_RE = re.compile(
    rf"(?s)^{re.escape(GENERATED_HEADER)}.*?^{re.escape(GENERATED_FOOTER)}", re.M)

OWN_LIBS: dict[ModuleKey, list[str]] = {  # modules shipping several archives
    "math": ["boost_math_c99", "boost_math_c99f", "boost_math_tr1", "boost_math_tr1f"],
    "test": ["boost_unit_test_framework", "boost_prg_exec_monitor",
             "boost_test_exec_monitor"],
    "serialization": ["boost_serialization", "boost_wserialization"],
}
EXTRA_ARCH: dict[ModuleKey, list[str]] = {"iostreams": ["libz.a", "libbz2.a"]}  # external static libs at test link

# merged layout: every header lands in one package, every built archive in the
# other. libboost-static depends on libboost-headers (headers pull no deps).
HEADERS_PKG: PkgName = "libboost-headers"
STATIC_PKG: PkgName = "libboost-static"
STATIC_RUN = ["libbzip2-static", "zlib-static"]  # archives linked by boost_iostreams' config
EXTRA_RUN: dict[ModuleKey, list[str]] = {"iostreams": STATIC_RUN}  # conda pkgs shipping those libs


def base_of(key: ModuleKey) -> str:
    """Module key as used in package/config names ('numeric~interval' ->
    'numeric_interval')."""
    return key.replace("~", "_")


def pkg_name(key: ModuleKey, compiled: set[ModuleKey]) -> PkgName:
    """Conda package name for a module: compiled modules ship static archives
    and get a '-static' suffix, header-only modules do not."""
    return f"boost-{base_of(key)}" + ("-static" if key in compiled else "")


def pin(dep: PkgName) -> str:
    """Version-pin a dependency on a sibling boost output (same 1.x minor
    line); external deps (zlib, bzip2) pass through unchanged."""
    return (f"${{{{ pin_subpackage('{dep}', upper_bound='x.x') }}}}"
            if dep.startswith(("boost-", "libboost-")) else dep)


def archives_for(mod: ModuleKey) -> list[str]:
    """Static archive paths shipped for one compiled module."""
    return [f"lib/lib{stem}.a" for stem in
            OWN_LIBS.get(mod, [f"boost_{mod}"])]


def basename(path: str) -> str:
    return path.rsplit("/", 1)[-1]


def cfg_path(key: ModuleKey) -> Claim:
    """CMake package config path generated for one module."""
    base = base_of(key)
    return f"lib/cmake/boost_{base}/boost_{base}Config.cmake"


def archive_of(mod: ModuleKey) -> str:
    """Primary static archive name for one compiled module."""
    return basename(archives_for(mod)[0])


def skip_from_build_sh() -> set[ModuleKey]:
    m = re.search(r'BOOST_SKIP_MODULES="([^"]*)"', SKIP_FILE.read_text())
    assert m, f"BOOST_SKIP_MODULES not found in {SKIP_FILE}"
    return set(m.group(1).split())


def load_boostdep() -> tuple[list[ModuleKey], dict[ModuleKey, set[ModuleKey]],
                             dict[ModuleKey, set[ModuleKey]]]:
    """(modules, header deps, buildable deps) from the vendored report.

    Reads the vendored boostdep report (gen_boostdep_deps.py). The report is
    per-release data: refuse to run against a bumped recipe version.
    """
    data = json.loads(BOOSTDEP_FILE.read_text())
    ctx = yaml.safe_load(RECIPE_FILE.read_text())["context"]
    want = f"boost-{ctx['version']}"
    assert data["_meta"]["boost_tag"] == want, \
        f"stale {BOOSTDEP_FILE.name}: {data['_meta']['boost_tag']} != {want}"
    modules: list[ModuleKey] = data["modules"]
    deps = {m: set(v) for m, v in data["deps"].items()}
    buildable = {m: set(v) for m, v in data["buildable"].items()}
    assert set(deps) == set(buildable) == set(modules), "report module set mismatch"
    return modules, deps, buildable


def parse_exceptions(root: Path, modules: set[ModuleKey]) -> dict[ModuleKey, list[str]]:
    exc_file = root / "tools" / "boostdep" / "depinst" / "exceptions.txt"
    extra: dict[ModuleKey, list[str]] = {}
    mod: ModuleKey | None = None
    for line in exc_file.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if not line.startswith("boost/"):
            mod = line.rstrip(":").replace("/", "~")
            continue
        if mod in modules:
            extra.setdefault(mod, []).append(line.removeprefix("boost/"))
    return extra


def build_ownership(root: Path, modules: list[ModuleKey]) -> tuple[dict[str, ModuleKey],
                                                                   dict[ModuleKey, list[str]]]:
    """(rel path below boost/ -> module, module -> sorted rel paths).

    A module owns its libs/<m>/include/boost tree plus the exceptions.txt
    assignments (exceptions win where both apply); together they cover the
    merged boost/ tree exactly, else this dies.
    """
    exc = parse_exceptions(root, set(modules))
    owner: dict[str, ModuleKey] = {p: m for m, ps in exc.items() for p in ps}
    for m in modules:
        inc = root / "libs" / m.replace("~", "/") / "include" / "boost"
        for p in walk_files(inc):
            rel = p.relative_to(inc).as_posix()
            prev = owner.setdefault(rel, m)
            if prev != m:
                raise SystemExit(f"double ownership: {rel}: {prev} vs {m}")
    merged = {p.relative_to(root / "boost").as_posix() for p in walk_files(root / "boost")}
    if set(owner) != merged:
        raise SystemExit(f"ownership mismatch: unowned {len(merged - set(owner))}, "
                         f"phantom {len(set(owner) - merged)}")
    files: dict[ModuleKey, list[str]] = {m: [] for m in modules}
    for rel, m in owner.items():
        files[m].append(rel)
    for fs in files.values():
        fs.sort()
    empty = [m for m in modules if not files[m]]
    if empty:
        raise SystemExit(f"modules with no files: {empty}")
    return owner, files


def claims_for(files: list[str], boost_dir: Path) -> list[Claim]:
    """Sorted include/boost/... entries for one module.

    A top-level entry becomes a glob when the module owns every physical file
    below it, an explicit file list when it shares it with another module
    (boost/detail/**, boost/numeric/**, ...).
    """
    groups: dict[str, list[str]] = {}
    for rel in files:
        groups.setdefault(rel.split("/", 1)[0], []).append(rel)
    entries: list[Claim] = []
    for top, rels in sorted(groups.items()):
        base = boost_dir / top
        if base.is_file():
            entries.append(f"include/boost/{top}")
        elif len(rels) == sum(1 for _ in walk_files(base)):
            entries.append(f"include/boost/{top}/**")
        else:
            entries += [f"include/boost/{r}" for r in rels]
    return entries


def walk_files(base: Path) -> Iterator[Path]:
    """Every file below base, following directory symlinks.

    `b2 headers` builds the merged boost/ tree out of symlinks and pathlib's
    `**` does not descend into symlinked dirs; os.walk(followlinks=True) does.
    """
    for dirpath, _dirs, names in os.walk(base, followlinks=True):
        for name in names:
            if name.startswith("."):  # .gitkeep/.gitignore are repo plumbing, not headers
                continue
            p = Path(dirpath) / name
            if not p.is_file():
                continue
            yield p


def iter_includes(text: str) -> Iterator[str]:
    """Include targets below boost/, without the .hpp suffix.

    Line comments are stripped first: a commented-out include is not a
    dependency.
    """
    for line in text.splitlines():
        for inc in INC_RE.findall(line.split("//", 1)[0]):
            yield inc.removeprefix("boost/").removesuffix(".hpp")


def topo_order(nodes: list[ModuleKey], edges: dict[ModuleKey, set[ModuleKey]]) \
        -> tuple[list[ModuleKey], set[tuple[ModuleKey, ModuleKey]]]:
    """Deps-first deterministic order over run-dep edges.

    Residual include cycles (real mutual textual deps, e.g. detail/algorithm
    <-> range/*) cannot be ordered: drop one edge per cycle. Callers must
    remove those edges from the package run lists too (the package built
    first in a pair would otherwise declare the second as a run dep and its
    eagerly-solved test env could not resolve).
    """
    edges = {n: set(ds) for n, ds in edges.items()}
    broken: set[tuple[ModuleKey, ModuleKey]] = set()
    while True:
        ts = graphlib.TopologicalSorter(edges)
        try:
            ts.prepare()
        except graphlib.CycleError as exc:
            cycle = exc.args[1][:-1]  # graphlib repeats the first node at the end
            src = max(cycle[:-1])
            dst = cycle[(cycle.index(src) + 1) % len(cycle)]
            edges[src].discard(dst)
            broken.add((src, dst))
            continue
        ready = sorted(ts.get_ready())
        order: list[ModuleKey] = []
        while ready:
            n = ready.pop(0)
            order.append(n)
            ts.done(n)
            ready.extend(ts.get_ready())
            ready.sort()
        assert len(order) == len(nodes), "could not order all outputs"
        assert len(broken) < 25, f"suspicious number of order breaks: {sorted(broken)}"
        return order, broken


class _Dumper(yaml.SafeDumper):
    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        return super().increase_indent(flow, False)

    def ignore_aliases(self, data: object) -> bool:
        return True


def _repr_none(dumper: yaml.SafeDumper, _: object):
    return dumper.represent_scalar("tag:yaml.org,2002:null", "")


def _repr_str(dumper: yaml.SafeDumper, data: str):
    # Keep generated multi-line build scripts readable.
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(type(None), _repr_none)
_Dumper.add_representer(str, _repr_str)


def emit_blocks(blocks: list[dict[str, object]]) -> str:
    """All output blocks as one YAML sequence."""
    text = yaml.dump({"outputs": blocks}, Dumper=_Dumper, default_flow_style=False,
                     sort_keys=False, width=10**9)
    return text.split("\n", 1)[1]  # drop the 'outputs:' wrapper line


def generated_region(generated: str) -> str:
    return f"{GENERATED_HEADER}\n{generated}{GENERATED_FOOTER}"


def write_generated(path: Path, generated: str) -> None:
    path.write_text(generated_region(generated) + "\n")


_UNSET = object()


def package_block(pkg: PkgName, script: str, files: list[Claim] | None = None,
                  run: list[PkgName] | object = _UNSET,
                  tests: list[dict[str, object]] | None = None) -> dict[str, object]:
    """One complete output block: package, build, requirements and tests."""
    build: dict[str, object] = {"script": script}
    if files is not None:
        build["files"] = {"include": files}
    requirements: dict[str, object] = {}
    if run is not _UNSET:  # omitted for dependency-free outputs
        requirements["run"] = run or None
    requirements["run_exports"] = [pin(pkg)]
    return {"package": {"name": pkg, "version": "${{ version }}"},
            "inherit": "build-cache", "build": build,
            "requirements": requirements, "tests": tests or []}


def contents_test(*, libs: list[str] | None = None,
                  includes: list[str] | None = None) -> dict[str, object]:
    """A package_contents test with only the non-empty sections."""
    contents: dict[str, list[str]] = {}
    if libs:
        contents["lib"] = libs
    if includes:
        contents["include"] = includes
    return {"package_contents": contents}


def script_test(name: str, extra_run: list[PkgName] | None = None) -> dict[str, object]:
    """One CMake script test block (goes under the output's 'tests:')."""
    requirements: dict[str, object] = {"build": ['${{ compiler("cxx") }}']}
    if extra_run:
        requirements["run"] = extra_run
    return {"script": [f"bash tests/build_tests_cmake.sh {name}"],
            "requirements": requirements,
            "files": {"recipe": ["tests/build_tests_cmake.sh",
                                 "tests/CMakeLists.txt",
                                 f"tests/test_{name}.cpp"]}}


def cfg_call(key: ModuleKey, kind: str, whole: list[str], deps: list[str]) -> str:
    """Build-script line: gen_cmake_configs.sh renders the config template at
    $PREFIX (single template for every module package, no inline heredocs)."""
    args = " ".join([base_of(key), kind, *whole])
    if deps:
        args += " -- " + " ".join(deps)
    return f'bash "$RECIPE_DIR/gen_cmake_configs.sh" {args}'


def compiled_cfg_call(key: ModuleKey, link: dict[ModuleKey, list[ModuleKey]]) -> str:
    """Config line for one compiled module: its archive plus link closure."""
    return cfg_call(key, "compiled", [archive_of(key)],
                    [archive_of(d) for d in link[key] if d != key]
                    + EXTRA_ARCH.get(key, []))


def all_libs(keys: list[ModuleKey]) -> list[str]:
    return sorted({l for k in keys for l in archives_for(k)})


def lib_names(libs: list[str]) -> list[str]:
    return [basename(l) for l in libs]


def cfg_files(keys: list[ModuleKey]) -> list[Claim]:
    return sorted(cfg_path(k) for k in keys)


def header_probe(claims: list[Claim], boost_dir: Path | None = None) -> str | None:
    """An include/-relative header path shipped by these claims (or None)."""
    for c in claims:
        rel = c.removeprefix("include/")
        if rel.endswith(HEADER_SUFFIXES):
            return rel
    if boost_dir is None:
        return None
    for c in claims:
        rel = c.removeprefix("include/boost/").removesuffix("/**")
        base = boost_dir / rel
        if c.endswith("/**") and base.is_dir():
            found = sorted(p for p in walk_files(base)
                           if p.suffix in HEADER_SUFFIXES)
            if found:
                return "boost/" + found[0].relative_to(boost_dir).as_posix()
    return None


def test_extra_reqs(tests_dir: Path, owner: dict[str, ModuleKey], key: ModuleKey,
                    compiled: set[ModuleKey]) -> list[PkgName]:
    """Test TUs may include headers of modules beyond the package's own
    shipped-header deps (e.g. test_array uses boost/functional/hash.hpp from
    boost-container_hash): scan the test file and return the owners of its
    includes."""
    f = tests_dir / f"test_{base_of(key)}.cpp"
    if not f.is_file():
        return []
    pkg = pkg_name(key, compiled)
    extra: set[PkgName] = set()
    for target in iter_includes(f.read_text(errors="ignore")):
        dep = owner.get(target) or owner.get(f"{target}.hpp")
        if dep is not None and pkg_name(dep, compiled) != pkg:
            extra.add(pkg_name(dep, compiled))
    return sorted(extra)


def header_only_tests(keys: list[ModuleKey], tests_dir: Path,
                      claims: dict[ModuleKey, list[Claim]], boost_dir: Path,
                      extra_for: Callable[[ModuleKey], list[PkgName]] | None = None) \
        -> tuple[list[dict[str, object]], list[str]]:
    """(script tests, probe headers) for header-only modules.

    Modules with a hand-written test get a CMake script test; the others are
    covered by a package_contents probe.
    """
    scripts: list[dict[str, object]] = []
    probes: list[str] = []
    for k in keys:
        base = base_of(k)
        if (tests_dir / f"test_{base}.cpp").is_file():
            scripts.append(script_test(base, extra_for(k) if extra_for else None))
        else:
            probe = header_probe(claims[k], boost_dir)
            assert probe, f"{k}: no probe header in claims {claims[k]}"
            probes.append(probe)
    return scripts, probes


def sync_recipe(region: str, update: bool) -> bool:
    """Check recipe.yaml's generated region, splicing it in when requested."""
    recipe = RECIPE_FILE.read_text()
    m = GENERATED_RE.search(recipe)
    assert m is not None, "no generated markers in recipe.yaml - run the splice step"
    if m.group(0) != region:
        if not update:
            print("ERROR: recipe.yaml generated region != recipe_outputs.yaml\n"
                  "       re-run with --update-recipe (or do the splice step)")
            return False
        recipe = recipe[:m.start()] + region + recipe[m.end():]
        RECIPE_FILE.write_text(recipe)
        m = GENERATED_RE.search(recipe)
        assert m is not None
    assert "  - package:" not in recipe[m.end():], \
        "stray package block after the generated region in recipe.yaml"
    return True


@dataclass(frozen=True)
class BoostTree:
    """Everything derived from the Boost checkout, independent of layout."""
    modules: list[ModuleKey]
    compiled: list[ModuleKey]
    header_only: list[ModuleKey]
    deps: dict[ModuleKey, set[ModuleKey]]
    buildable: dict[ModuleKey, set[ModuleKey]]
    link: dict[ModuleKey, list[ModuleKey]]
    owner: dict[str, ModuleKey]
    claims: dict[ModuleKey, list[Claim]]
    tests_dir: Path
    boost_dir: Path


def load_tree(root: Path) -> BoostTree:
    boost_dir = root / "boost"
    assert (root / "libs").is_dir() and boost_dir.is_dir(), f"bad boost root: {root}"
    modules, bd_deps, bd_buildable = load_boostdep()
    modset = set(modules)
    skip = skip_from_build_sh()
    assert skip <= modset, f"skip list has non-modules: {sorted(skip - modset)}"
    # a module is compiled iff it has a src/ tree (b2 builds its archive from it)
    compiled = sorted({m for m in modset
                       if (root / "libs" / m.replace("~", "/") / "src").is_dir()} - skip)
    header_only = sorted(modset - set(compiled))
    owner, files = build_ownership(root, modules)
    claims = {k: claims_for(files[k], boost_dir) for k in modules}
    link = {m: closure_order(bd_buildable, set(compiled), m) for m in compiled}
    deps = {k: {d for d in bd_deps.get(k, set()) if d != k} for k in modules}
    return BoostTree(modules, compiled, header_only, deps, bd_buildable, link,
                     owner, claims, HERE.parent / "tests", boost_dir)


def write_deps(tree: BoostTree, path: Path) -> None:
    data: dict[str, object] = {"_modules": tree.compiled, "_header_only": tree.header_only}
    for m in tree.compiled:
        data[m] = {"direct": sorted(pkg_name(d, tree.compiled) for d in tree.deps[m]),
                   "compiled_direct": sorted(d for d in tree.buildable[m]
                                             if d in tree.compiled),
                   "link_closure": tree.link[m],
                   "files": tree.claims[m]}
    for k in tree.header_only:
        data[k] = {"deps": sorted(pkg_name(d, tree.compiled) for d in tree.deps[k]),
                   "files": tree.claims[k]}
    path.write_text(json.dumps(data, indent=2))


def modules_blocks(tree: BoostTree) -> list[dict[str, object]]:
    """Historical layout: one output per module plus two meta packages."""
    edges = {k: set(tree.deps[k]) for k in tree.modules}
    for m in tree.compiled:
        edges[m] |= {d for d in tree.buildable[m] if d in tree.compiled}
    order, broken = topo_order(tree.modules, edges)

    def run_deps(key: ModuleKey) -> list[PkgName]:
        reqs = {pkg_name(d, tree.compiled) for d in tree.deps[key]
                if (key, d) not in broken}
        if key in tree.compiled:
            reqs |= {pkg_name(d, tree.compiled) for d in tree.buildable[key]
                     if d in tree.compiled}
            reqs |= set(EXTRA_RUN.get(key, []))
        return sorted(reqs)

    def module_block(key: ModuleKey, libs: list[str], script: str,
                     tests: list[dict[str, object]]) -> dict[str, object]:
        return package_block(pkg_name(key, tree.compiled), script,
                             libs + tree.claims[key] + [cfg_path(key)],
                             [pin(d) for d in run_deps(key)] or None, tests)

    def compiled_block(m: ModuleKey) -> dict[str, object]:
        libs = archives_for(m)
        probe = header_probe(tree.claims[m])
        return module_block(
            m, libs, compiled_cfg_call(m, tree.link),
            [contents_test(libs=lib_names(libs),
                           includes=[probe] if probe else None),
             script_test(m, test_extra_reqs(tree.tests_dir, tree.owner, m, tree.compiled))])

    def ho_block(k: ModuleKey) -> dict[str, object]:
        scripts, probes = header_only_tests(
            [k], tree.tests_dir, tree.claims, tree.boost_dir,
            lambda key: test_extra_reqs(tree.tests_dir, tree.owner, key, tree.compiled))
        return module_block(k, [], cfg_call(k, "header-only", [], []),
                            scripts + [contents_test(includes=[p]) for p in probes])

    def meta_block(name: PkgName, roster: list[PkgName]) -> dict[str, object]:
        return package_block(name, 'echo "Collecting files from cache"',
                             run=[pin(d) for d in roster])

    return [compiled_block(k) if k in tree.compiled else ho_block(k) for k in order] + [
        meta_block("boost-headers",
                   sorted(pkg_name(k, tree.compiled) for k in tree.header_only)),
        meta_block("boost-cpp",
                   sorted(pkg_name(m, tree.compiled) for m in tree.modules))]


def merged_blocks(tree: BoostTree) -> list[dict[str, object]]:
    """Current layout: one headers package plus one static-archive package."""
    def headers_block() -> dict[str, object]:
        # Ownership checks in build_ownership guarantee that include/boost/**
        # is exactly the merged tree, whichever module owns which header.
        build = "\n".join(cfg_call(k, "header-only", [], []) for k in tree.header_only)
        tests, probes = header_only_tests(tree.header_only, tree.tests_dir,
                                          tree.claims, tree.boost_dir)
        # The whole tree is here, so also probe one header per compiled module
        # (the per-module recipe did this in the compiled packages).
        probes += [p for m in tree.compiled if (p := header_probe(tree.claims[m]))]
        if probes:
            tests.insert(0, contents_test(includes=probes))
        return package_block(HEADERS_PKG, build,
                             ["include/boost/**"] + cfg_files(tree.header_only),
                             tests=tests)

    def static_block() -> dict[str, object]:
        libs = all_libs(tree.compiled)
        build = "\n".join(compiled_cfg_call(m, tree.link) for m in tree.compiled)
        tests: list[dict[str, object]] = [contents_test(libs=lib_names(libs))]
        for m in tree.compiled:
            base = base_of(m)
            assert (tree.tests_dir / f"test_{base}.cpp").is_file(), \
                f"compiled module {m} has no tests/test_{base}.cpp"
            tests.append(script_test(base))
        return package_block(STATIC_PKG, build, libs + cfg_files(tree.compiled),
                             [pin(HEADERS_PKG)] + STATIC_RUN, tests)

    return [headers_block(), static_block()]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("boost_root", help="Boost git checkout at the release tag")
    ap.add_argument("out_dir", nargs="?", default=str(OUT_DEFAULT),
                    help="output directory (default: scripts/out)")
    ap.add_argument("--layout", choices=("merged", "modules"), default="merged",
                    help="merged = two packages (default); modules = historical layout")
    ap.add_argument("--update-recipe", action="store_true",
                    help="splice the generated region into recipe.yaml on drift")
    a = ap.parse_args(argv)

    out_dir = Path(a.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tree = load_tree(Path(a.boost_root))

    deps_file = out_dir / "deps.json"
    if deps_file.is_file():  # optional baseline, the first run has none
        old = json.loads(deps_file.read_text())["_modules"]
        assert tree.compiled == old, \
            f"compiled roster drift: {set(tree.compiled) ^ set(old)}"
    write_deps(tree, deps_file)

    if a.layout == "modules":
        generated = emit_blocks(modules_blocks(tree))
        modules_out = out_dir / "modules"
        modules_out.mkdir(parents=True, exist_ok=True)
        write_generated(modules_out / "recipe_outputs.yaml", generated)
        print(f"OK: modules layout: {len(tree.compiled)} compiled + "
              f"{len(tree.header_only)} header-only + 2 metas -> "
              f"{modules_out / 'recipe_outputs.yaml'}")
        return 0

    generated = emit_blocks(merged_blocks(tree))
    write_generated(out_dir / "recipe_outputs.yaml", generated)
    if not sync_recipe(generated_region(generated), a.update_recipe):
        return 1
    print(f"OK: merged layout: {HEADERS_PKG} ({len(tree.header_only)} header-only "
          f"modules) + {STATIC_PKG} ({len(tree.compiled)} compiled modules); "
          f"generated region byte-identical in recipe.yaml")
    return 0


def closure_order(direct: dict[ModuleKey, set[ModuleKey]], compiled: set[ModuleKey],
                  mod: ModuleKey) -> list[ModuleKey]:
    """Post-order DFS: dependencies before dependents (valid static link order)."""
    out: list[ModuleKey] = []
    seen = {mod}

    def visit(m: ModuleKey) -> None:
        for d in sorted(direct.get(m, set())):
            if d in compiled and d not in seen:
                seen.add(d)
                visit(d)
                out.append(d)

    visit(mod)
    return out


if __name__ == "__main__":
    sys.exit(main())
