#!/bin/bash
set -euo pipefail

mkdir -p build
cd build

emcmake cmake ${CMAKE_ARGS} \
    -GNinja \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="${PREFIX}" \
    -DCMAKE_INSTALL_LIBDIR=lib \
    -DCMAKE_EXE_LINKER_FLAGS="-sNODERAWFS=1 -sFORCE_FILESYSTEM=1" \
    -DBUILD_SHARED_LIBS=OFF \
    -DBUILD_TESTING=OFF \
    -DBUILD_EXAMPLES=OFF \
    -DITK_BUILD_DEFAULT_MODULES=ON \
    -DITK_FORBID_DOWNLOADS=ON \
    -DDO_NOT_BUILD_ITK_TEST_DRIVER=ON \
    -DITK_USE_GPU=OFF \
    -DITK_DEFAULT_THREADER=Platform \
    -DITK_USE_FFTWD=OFF \
    -DITK_USE_FFTWF=OFF \
    -DITK_USE_SYSTEM_FFTW=OFF \
    -DITK_USE_SYSTEM_ZLIB=ON \
    -DITK_USE_SYSTEM_PNG=ON \
    -DITK_USE_SYSTEM_JPEG=ON \
    -DITK_USE_SYSTEM_TIFF=ON \
    -DITK_USE_SYSTEM_EXPAT=ON \
    -DITK_USE_SYSTEM_EIGEN=OFF \
    -DITK_USE_SYSTEM_HDF5=OFF \
    -DITK_USE_SYSTEM_GDCM=OFF \
    -DOPJ_USE_THREAD=OFF \
    -DH5_HAVE_GETPWUID=OFF \
    "${SRC_DIR}"

ninja -j"${CPU_COUNT}"
ninja install
